import {createHash} from 'node:crypto';
import {existsSync, lstatSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import type {BrainDB} from '../core/database.ts';
import {BrainError} from '../core/models.ts';

// Implementation handoff (F20): approved memory never mutates the repository by itself.
// The user previews this exact file and confirms its hash before anything is written.
export const HANDOFF_FILE = '.personal-brain/preferences.md';
const sha = (text: string) => createHash('sha256').update(text).digest('hex');

const START = '<!-- personal-brain:start — generated; edit styles in Personal Brain -->';
const END = '<!-- personal-brain:end -->';
/**
 * Native instruction files read by agents without a Personal Brain connector. Shared files
 * (managed) get one marked block, so the user's own content in them is kept.
 */
export const HANDOFF_TARGETS = {
  preferences: {path: HANDOFF_FILE, label: 'Personal Brain file', managed: false, header: ''},
  agents: {
    path: 'AGENTS.md',
    label: 'AGENTS.md — Codex and most other agents',
    managed: true,
    header: '',
  },
  claude: {path: 'CLAUDE.md', label: 'CLAUDE.md — Claude Code', managed: true, header: ''},
  gemini: {path: 'GEMINI.md', label: 'GEMINI.md — Gemini CLI', managed: true, header: ''},
  copilot: {
    path: '.github/copilot-instructions.md',
    label: 'GitHub Copilot instructions',
    managed: true,
    header: '',
  },
  cursor: {
    path: '.cursor/rules/personal-brain.mdc',
    label: 'Cursor rule',
    managed: false,
    header: '---\ndescription: Working preferences from Personal Brain\nalwaysApply: true\n---\n\n',
  },
} as const;
type Target = keyof typeof HANDOFF_TARGETS;

function repository(db: BrainDB, projectId: string) {
  db.project(projectId);
  const row = db.db.prepare('SELECT value FROM meta WHERE key=?').get('repository:' + projectId) as
    {value: string} | undefined;
  if (!row) {
    throw new BrainError('Link this project to a repository folder first', 'NOT_FOUND', 404);
  }
  return row.value;
}
function target(raw: unknown): Target {
  const key = raw ?? 'preferences';
  if (typeof key !== 'string' || !Object.hasOwn(HANDOFF_TARGETS, key)) {
    throw new BrainError('Unknown file target');
  }
  return key as Target;
}
/** Replaces the marked block, or appends one, leaving the rest of a shared file untouched. */
function mergeBlock(existing: string | null, body: string) {
  const block = `${START}\n${body.trim()}\n${END}`;
  if (!existing?.trim()) {
    return block + '\n';
  }
  const start = existing.indexOf('<!-- personal-brain:start');
  if (start < 0) {
    return existing.trimEnd() + '\n\n' + block + '\n';
  }
  const end = existing.indexOf(END, start);
  if (end < 0) {
    throw new BrainError('The Personal Brain block in this file has no end marker; fix it first');
  }
  return existing.slice(0, start) + block + existing.slice(end + END.length);
}

/** A project's approved preferences as one Markdown document, for files and prompts. */
export function preferencesText(db: BrainDB, projectId: string) {
  const project = db.project(projectId);
  const styles = db
    .scopedRecords(projectId)
    .filter((r) => r.kind === 'preference' && !r.compatibility);
  const body = [
    `# ${project.name} — working preferences`,
    '',
    'Generated by Personal Brain from approved preferences for this project. Review before committing;',
    'enforce rules with the repository formatter, linter or CI where possible.',
    '',
    ...styles.flatMap((r) => [
      `## ${r.title} (v${r.version}, ${r.source})`,
      '',
      r.content.trim(),
      '',
    ]),
  ].join('\n');
  return {body, styles};
}
export function handoffPreview(db: BrainDB, projectId: string, rawTarget?: unknown) {
  const key = target(rawTarget),
    spec = HANDOFF_TARGETS[key];
  const root = repository(db, projectId);
  const {body, styles} = preferencesText(db, projectId);
  const file = join(root, spec.path);
  const existing = existsSync(file) ? readFileSync(file, 'utf8') : null;
  const content = spec.managed ? mergeBlock(existing, body) : spec.header + body;
  return {
    target: key,
    path: spec.path,
    managed: spec.managed,
    content,
    contentHash: sha(content),
    existingHash: existing === null ? null : sha(existing),
    unchanged: existing === content,
    autoUpdate: autoExports(db, projectId).includes(key),
    styles: styles.length,
    // ponytail: chars/4 estimate; these files load on every prompt, so size matters.
    approxTokens: Math.round(content.length / 4),
  };
}

export function handoffWrite(
  db: BrainDB,
  projectId: string,
  contentHash: unknown,
  existingHash: unknown,
  rawTarget?: unknown,
) {
  const preview = handoffPreview(db, projectId, rawTarget);
  if (preview.contentHash !== contentHash || preview.existingHash !== (existingHash ?? null)) {
    throw new BrainError('Preferences or the file changed; preview again', 'CONFLICT', 409);
  }
  const root = repository(db, projectId);
  // Refuse symlinks anywhere on the path so the write cannot be redirected outside the repository.
  const parts = preview.path.split('/');
  for (let i = 1; i <= parts.length; i++) {
    const path = join(root, ...parts.slice(0, i));
    if (existsSync(path) && lstatSync(path).isSymbolicLink()) {
      throw new BrainError('Refusing to write through a symbolic link: ' + path);
    }
  }
  const file = join(root, preview.path);
  mkdirSync(dirname(file), {recursive: true});
  writeFileSync(file, preview.content);
  return {written: preview.path, contentHash: preview.contentHash};
}

/**
 * Rule files written earlier that no longer match the approved styles. Agents without a
 * Personal Brain connection read these files, so a stale one silently splits the "one style".
 */
export function staleExports(db: BrainDB) {
  const stale: {projectId: string; project: string; path: string}[] = [];
  for (const project of db.projects()) {
    const row = db.db.prepare('SELECT 1 FROM meta WHERE key=?').get('repository:' + project.id);
    if (!row) {
      continue;
    }
    for (const key of Object.keys(HANDOFF_TARGETS) as Target[]) {
      const spec = HANDOFF_TARGETS[key];
      try {
        const file = join(repository(db, project.id), spec.path);
        if (!existsSync(file)) {
          continue;
        }
        // A shared file without our block was never exported; leave it alone.
        if (spec.managed && !readFileSync(file, 'utf8').includes('<!-- personal-brain:start')) {
          continue;
        }
        if (!handoffPreview(db, project.id, key).unchanged) {
          stale.push({projectId: project.id, project: project.name, path: spec.path});
        }
      } catch {
        /* Unreadable or broken file: the project page shows the error on preview. */
      }
    }
  }
  return stale;
}

const AUTO = 'auto-export:';
/** Files the user chose, after seeing a preview, to keep in step with the approved styles. */
export function autoExports(db: BrainDB, projectId: string): Target[] {
  const row = db.db.prepare('SELECT value FROM meta WHERE key=?').get(AUTO + projectId) as
    {value: string} | undefined;
  return row
    ? (JSON.parse(row.value) as Target[]).filter((t) => Object.hasOwn(HANDOFF_TARGETS, t))
    : [];
}
export function setAutoExport(
  db: BrainDB,
  projectId: string,
  rawTarget: unknown,
  enabled: unknown,
) {
  db.project(projectId);
  const key = target(rawTarget);
  const next = new Set(autoExports(db, projectId));
  if (enabled === true) {
    next.add(key);
  } else {
    next.delete(key);
  }
  if (next.size) {
    db.db
      .prepare('INSERT OR REPLACE INTO meta(key,value) VALUES(?,?)')
      .run(AUTO + projectId, JSON.stringify([...next]));
  } else {
    db.db.prepare('DELETE FROM meta WHERE key=?').run(AUTO + projectId);
  }
  return {target: key, autoUpdate: next.has(key)};
}
/**
 * Background step: rewrites opted-in files whose content no longer matches the styles, so agents
 * that read rule files instead of Personal Brain follow the same version. Same checks as a manual write.
 */
export function syncExports(db: BrainDB) {
  const results: {projectId: string; path: string; error?: string}[] = [];
  const rows = db.db.prepare('SELECT key FROM meta WHERE key LIKE ?').all(AUTO + '%') as {
    key: string;
  }[];
  for (const {key} of rows) {
    const projectId = key.slice(AUTO.length);
    for (const t of autoExports(db, projectId)) {
      try {
        const preview = handoffPreview(db, projectId, t);
        if (!preview.unchanged) {
          handoffWrite(db, projectId, preview.contentHash, preview.existingHash, t);
          results.push({projectId, path: preview.path});
        }
      } catch (e) {
        results.push({
          projectId,
          path: HANDOFF_TARGETS[t].path,
          error: e instanceof Error ? e.message : String(e),
        });
      }
    }
  }
  return results;
}
